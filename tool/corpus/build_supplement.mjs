import fs from 'node:fs';

const input = JSON.parse(fs.readFileSync('assets/corpus/smcp_supplement.json', 'utf8'));
const normalize = s => s.toLowerCase().replaceAll('’', "'").trim().replace(/\s+/g, ' ').replace(/[.!。！]+$/, '').trim();
const base = JSON.parse(fs.readFileSync('assets/corpus/maritime_turns.json', 'utf8'));
const existing = new Set(base.pairs.map(p => normalize(p.en)));
const seen = new Set();
const ids = new Set();
for (const entry of input.entries) {
  if (!entry.en?.trim() || !entry.zh?.trim() ||
      !entry.sourceRecordIds?.length || !entry.referencePdfPages?.length ||
      entry.reviewStatus !== 'editorially_reviewed' || /\.{2,}|[\[\]{}~]/.test(entry.en)) {
    throw Error(`Incomplete or unreviewed entry: ${entry.id}`);
  }
  const key = normalize(entry.en);
  if (seen.has(key) || existing.has(key) || ids.has(entry.id)) {
    throw Error(`Duplicate supplement phrase: ${entry.id}`);
  }
  seen.add(key);
  ids.add(entry.id);
}
const q = s => JSON.stringify(s).replace(/\$/g, '\\$');
const code = `// Generated by tool/corpus/build_supplement.mjs from reviewed JSON.\nimport 'maritime_corpus.dart';\n\nabstract final class SmcpSupplement {\n  static const pairs = <CorpusPair>[\n${input.entries.map(p => `    CorpusPair(${q(p.id)}, ${q(p.category)}, ${q(p.en)}, ${q(p.zh)}, true),`).join('\n')}\n  ];\n}\n`;
fs.writeFileSync('lib/config/smcp_supplement.dart', code);
console.log(`Generated ${input.entries.length} reviewed SMCP supplement pairs.`);
